"""AB1: write configs/rl_ablation_full.yaml and configs/rl_ablation_weak.yaml from the phase-2c b2048 config (the one that ran 1,433 stable steps), so that the two arms are
BYTE-IDENTICAL except for `model_name`, `out_dir` and `run_name` (asserted at the end).

    python scripts/ab1_make_configs.py --template configs/rl_rtxpro_phase2c_b2048.yaml --out-dir configs \
        --weak-model /workspace/jobs/ab1/models/sft_weak --full-model /workspace/jobs/ab1/models/sft_final [--steps-b64 100 --steps-b256 400]

What changes against phase 2c (everything else - reward, calibration v7, GlotLID guard, consensus, length / word-ratio / diacritic terms, group 16, std-normalised advantage,
lr 2e-6, k3c KL 0.05, KL guard, language draw weights, seed - is copied verbatim): fresh start from `model_name` (no `last/`; the KL reference is the start model, the optimizer is
FRESH for both arms), prompts = an AB1 subset of rl_prompts_v3 (b64 + b256 only), curriculum b64 -> b256 (no b512 / b1024 / b2048 / mixed), no archive, no Hub, evaluation every 50 steps,
snapshots `snap_step<export>` and `snap_step<steps>` (bf16 HF directories) for the FLORES+ evaluation.
"""
from __future__ import annotations

import argparse
import os
import re
import sys


def set_line(text: str, key: str, value: str, comment: str = "") -> str:
    pat = re.compile(rf"^{re.escape(key)}:.*$", re.M)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"key {key!r}: expected exactly one top-level line, found {len(pat.findall(text))}")
    return pat.sub(lambda m: f"{key}: {value}" + (f"  # {comment}" if comment else ""), text)


def set_block(text: str, key: str, entries) -> str:
    pat = re.compile(rf"^{re.escape(key)}:[^\n]*\n(?:[ \t]+[^\n]*\n)+", re.M)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"block {key!r}: expected exactly one, found {len(pat.findall(text))}")
    body = "".join(f"  {k}: {v}\n" for k, v in entries)
    return pat.sub(lambda m: f"{key}:\n{body}", text)


def build(template: str, model: str, run_name: str, prompts: str, runs_dir: str, steps_b64: int, steps_b256: int, export: int, ps64: int, ps256: int) -> str:
    t = open(template, encoding="utf-8").read()
    steps = steps_b64 + steps_b256
    t = set_line(t, "model_name", model, "AB1: the START checkpoint of the arm; also the frozen KL reference; a FRESH optimizer (no last/ state is prepared)")
    t = set_line(t, "prompts_path", prompts, "AB1: 2,500 b64 + 2,500 b256 rows per language drawn at random from rl_prompts_v3 (scripts/ab1_make_prompts.py); identical for both arms")
    t = set_line(t, "out_dir", f"{runs_dir}/{run_name}")
    compl = (steps_b64 * ps64 + steps_b256 * ps256) * 16
    t = set_line(t, "steps", str(steps), f"AB1: {steps_b64} b64 steps x {ps64} prompts + {steps_b256} b256 steps x {ps256} prompts, group 16 = {compl:,} completions per arm")
    t = set_line(t, "prompts_per_step", str(ps64))
    t = set_line(t, "max_new_tokens", "1280")
    t = set_line(t, "max_src_tokens", "256", "AB1: b64 + b256 windows only")
    t = set_line(t, "vllm_max_model_len", "4096", "AB1: b256 prompt up to ~450 + 1,280 new tokens")
    t = set_block(t, "curriculum_steps", [("b64", steps_b64), ("b256", steps_b256)])
    t = set_block(t, "prompts_per_step_by_bin", [("b64", ps64), ("b256", ps256), ("mixed", ps256)])
    t = set_block(t, "max_new_tokens_by_bin", [("b64", 384), ("b256", 1280), ("mixed", 1280)])
    t = t.replace("/workspace/sft_build/gemma_mt/calibration/", "/workspace/jobs/ab1/gemma_mt/calibration/")   # the AB1 tree's own copy (the shared symlink tree may change under a long run)
    t = set_line(t, "eval_every", "50")
    t = set_line(t, "benchmark_eval_every", "50")
    t = set_line(t, "save_every", "100", "AB1: `last/` is a symlink into /dev/shm (3.2 GB, rewritten via a .tmp copy: no room on the disk); resumable after a trainer crash, not after a box restart")
    t = set_line(t, "hub_repo_id", "null", "AB1: nothing is pushed")
    t = set_line(t, "hub_stage_branches", "false")
    t = set_line(t, "hub_latest_every", "0")
    t = set_line(t, "archive", "false")
    t = set_line(t, "archive_path", "null")
    t = set_line(t, "run_name", run_name)
    t = set_line(t, "seed", "1234", "identical for both arms: same prompts at every step, same hold-out, same language draws")
    t = re.sub(r"^keep_single_checkpoint:.*$", "keep_single_checkpoint: true         # local disk: only last/ (resumable) + the AB1 snapshots below", t, flags=re.M)
    t = t.rstrip("\n") + f"\nexport_steps: [{export}]               # AB1: also snap_step{export} and snap_step{steps} (bf16 HF dirs; the last step is added automatically)\nexport_dtype: bfloat16\n"
    head = (f"# AB1 ablation arm '{run_name}' (RL-vs-SFT-data ablation, paper section 8.4): generated by scripts/ab1_make_configs.py from the phase-2c b2048 config. The two arms differ ONLY in\n"
            "# model_name / out_dir / run_name. Settings: group 16, std-normalised advantage, lr 2e-6, k3c KL 0.05 + KL guard, language_alpha 0 with the x2.5 weak-language weights, fresh optimizer,\n"
            f"# {ps64} (b64) / {ps256} (b256) prompts per step as in phase 2c, curriculum b64 {steps_b64} -> b256 {steps_b256}, no science / anchors / ensemble / long documents.\n")
    return head + t


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--weak-model", default="/workspace/jobs/ab1/models/sft_weak")
    ap.add_argument("--full-model", default="/workspace/jobs/ab1/models/sft_final")
    ap.add_argument("--prompts", default="/workspace/jobs/ab1/data/rl_prompts_ab1")
    ap.add_argument("--runs-dir", default="/workspace/jobs/ab1/runs")
    ap.add_argument("--steps-b64", type=int, default=100)
    ap.add_argument("--steps-b256", type=int, default=300)
    ap.add_argument("--per-step-b64", type=int, default=64)
    ap.add_argument("--per-step-b256", type=int, default=48)
    ap.add_argument("--export", type=int, default=200)
    a = ap.parse_args(argv)
    os.makedirs(a.out_dir, exist_ok=True)
    out = {}
    for arm, model, name in (("weak", a.weak_model, "ab1_weak"), ("full", a.full_model, "ab1_full")):
        out[arm] = build(a.template, model, name, a.prompts, a.runs_dir, a.steps_b64, a.steps_b256, a.export, a.per_step_b64, a.per_step_b256)
        with open(os.path.join(a.out_dir, f"rl_ablation_{arm}.yaml"), "w", encoding="utf-8") as f:
            f.write(out[arm])
    # the arms must differ only in the three arm-specific values
    norm = {k: re.sub(r"ab1_(weak|full)", "ARM", v.replace(a.weak_model, "MODEL").replace(a.full_model, "MODEL")) for k, v in out.items()}
    if norm["weak"] != norm["full"]:
        raise SystemExit("the two arm configs differ in more than model_name / out_dir / run_name")
    print("wrote", [os.path.join(a.out_dir, f"rl_ablation_{k}.yaml") for k in out], "- identical except model_name / out_dir / run_name")
    return 0


if __name__ == "__main__":
    sys.exit(main())

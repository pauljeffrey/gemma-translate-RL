"""E1 pairwise benchmark comparison: markdown tables of the report from the CSVs of reports/data/pairwise_benchmark_comparison/.

    python gemma_mt/scripts/pairwise_make_tables.py     ->  reports/data/pairwise_benchmark_comparison/tables.md  (all tables, one file)

Every table of reports/pairwise_benchmark_comparison_2026-10-23.md is a copy of one section of tables.md (so the numbers of the report can be regenerated)."""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
D = os.environ.get("PAIRWISE_DATA", os.path.join(REPO, "reports", "data", "pairwise_benchmark_comparison"))
R5 = os.path.join(REPO, "reports", "data", "final_model_runs")
ML = {"chrf": "chrF++ (all rows)", "chrf_sub": "chrF++ (rows scored by COMET)", "afri_ref": "AfriCOMET reference-based", "ssa_ref": "SSA-COMET-MTL reference-based",
      "ens_ref": "majority of the 3 reference-based", "afri_qe": "AfriCOMET-QE (RL reward model)", "ssa_qe": "SSA-COMET-MTL QE", "ens_qe": "both QE metrics agree",
      "ens_unan": "all 3 reference-based agree"}
BL = {"flores_plus": "FLORES+", "ntrex": "NTREX-128", "mafand": "MAFAND-MT", "smol_sent": "SmolSent", "ibom_mt": "IbomMT", "flores_moz": "FLORES-MOZ", "salt": "SALT",
      "glot_story": "GlotStoryBook", "ALL": "all benchmarks (per-language pooled)"}


def rd(sub, name):
    return pd.read_csv(os.path.join(D, sub, name))


def md(df, cols=None):
    cols = cols or list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out) + "\n"


def pct(x, d=1):
    return "" if pd.isna(x) else f"{100 * x:.{d}f}"


def ci_fmt(d, lo, hi, nd=2, plus=True):
    s = "+" if plus and d >= 0 else ""
    sl = "+" if plus and lo >= 0 else ""
    sh = "+" if plus and hi >= 0 else ""
    return f"{s}{d:.{nd}f} [{sl}{lo:.{nd}f}, {sh}{hi:.{nd}f}]"


def pstr(p):
    return "<1e-300" if p == 0 or p < 1e-300 else (f"{p:.1e}" if p < 1e-3 else f"{p:.3f}")


def headline(m, sub, b="ALL", scope="all_langs", metrics=("chrf", "chrf_sub", "afri_ref", "ssa_ref", "ens_ref", "afri_qe", "ssa_qe")):
    rows = []
    for k in metrics:
        r = m[(m.subset == sub) & (m.b == b) & (m.scope == scope) & (m.metric == k)]
        if not len(r):
            continue
        r = r.iloc[0]
        nd = 3 if k in ("afri_ref", "ssa_ref", "afri_qe", "ssa_qe") else 2
        if k.startswith("ens"):
            rows.append(dict(metric=ML[k], langs=int(r.n_langs), sentences=int(r.n_sent), SFT="", RL="", delta="",
                             **{"win / tie / loss % (macro)": f"{pct(r.macro_win)} / {pct(r.macro_tie)} / {pct(r.macro_loss)}",
                                "RL preferred % of non-tied [95% CI] (micro)": f"{pct(r.micro_pref)} [{pct(r.micro_pref_lo)}, {pct(r.micro_pref_hi)}]",
                                "sign test p": pstr(r.micro_p_sign)}))
            continue
        rows.append(dict(metric=ML[k], langs=int(r.n_langs), sentences=int(r.n_sent), SFT=f"{r.mean_a:.{nd}f}", RL=f"{r.mean_b:.{nd}f}",
                         delta=ci_fmt(r.delta, r.delta_lo, r.delta_hi, nd),
                         **{"win / tie / loss % (macro)": f"{pct(r.macro_win)} / {pct(r.macro_tie)} / {pct(r.macro_loss)}",
                            "RL preferred % of non-tied [95% CI] (micro)": f"{pct(r.micro_pref)} [{pct(r.micro_pref_lo)}, {pct(r.micro_pref_hi)}]",
                            "sign test p": pstr(r.micro_p_sign)}))
    return md(pd.DataFrame(rows))


def main():
    out = []
    P = out.append
    m = rd("main", "macro.csv")
    u = rd("main", "unit_stats.csv")
    P("# Tables of the E1 pairwise benchmark comparison (generated by gemma_mt/scripts/pairwise_make_tables.py)\n")
    P("Macro = mean over languages (each language's sentences resampled independently, B=1000); micro = sentences pooled (strata = language); `RL preferred` = wins / (wins + losses). Tie thresholds: chrF++ 1.0, COMET-family 0.01.\n")
    for sub in ("no_pair", "clean", "all"):
        P(f"## T1-{sub}. Headline, subset `{sub}`, all benchmarks, per-language pooled, macro over languages\n")
        P(headline(m, sub))
    # per benchmark
    P("## T2. By benchmark (`no_pair`): delta [95% CI] and RL-preferred share per metric\n")
    rows = []
    for b in ["flores_plus", "ntrex", "mafand", "smol_sent", "ibom_mt", "flores_moz", "salt", "glot_story"]:
        row = {"benchmark": BL[b]}
        for k in ("chrf", "afri_ref", "ssa_ref", "afri_qe", "ssa_qe"):
            r = m[(m.subset == "no_pair") & (m.b == b) & (m.scope == "all_langs") & (m.metric == k)]
            if not len(r):
                row[ML[k]] = ""
                continue
            r = r.iloc[0]
            nd = 2 if k == "chrf" else 3
            row[ML[k]] = f"{r.delta:+.{nd}f} ({pct(r.micro_pref, 0)}%) n={int(r.n_langs)}"
        rows.append(row)
    P(md(pd.DataFrame(rows)))
    P("Cells: macro delta (RL - SFT) (RL-preferred % of non-tied sentences, micro) and the number of languages. The neural metrics cover the AfriCOMET-covered languages only.\n")
    # groups
    P("## T3. By training group / family / resource tier (`no_pair`, all benchmarks)\n")
    scopes = [s for s in m.scope.unique()]
    rows = []
    for s in scopes:
        row = {"scope": s}
        ok = False
        for k in ("chrf", "afri_ref", "ssa_ref", "afri_qe", "ssa_qe"):
            r = m[(m.subset == "no_pair") & (m.b == "ALL") & (m.scope == s) & (m.metric == k)]
            if not len(r):
                row[ML[k]] = ""
                continue
            ok = True
            r = r.iloc[0]
            nd = 2 if k == "chrf" else 3
            row[ML[k]] = f"{r.delta:+.{nd}f} [{r.delta_lo:+.{nd}f}, {r.delta_hi:+.{nd}f}]; {pct(r.micro_pref, 0)}%"
            row["langs"] = int(r.n_langs) if k == "chrf" else row.get("langs", "")
        if ok:
            rows.append(row)
    P(md(pd.DataFrame(rows), ["scope", "langs"] + [ML[k] for k in ("chrf", "afri_ref", "ssa_ref", "afri_qe", "ssa_qe")]))
    # per language
    P("## T4. Per language (`no_pair`, all benchmarks pooled)\n")
    uu = u[(u.subset == "no_pair") & (u.b == "ALL")]
    fl = rd("main", "flags.csv")
    fl = fl[(fl.subset == "no_pair") & (fl.b == "ALL")].set_index("iso")
    iso_order = uu.drop_duplicates("iso").sort_values(["group", "iso"])["iso"].tolist()
    rows = []
    for iso in iso_order:
        g = uu[uu.iso == iso].set_index("metric")
        row = {"iso": iso, "group": g.group.iloc[0].replace("qe_validated", "qe").replace("consensus_only", "cons").replace("sft_only", "sft-only"), "n": int(g.loc["chrf", "n"])}
        for k in ("chrf", "afri_ref", "ssa_ref", "afri_qe", "ssa_qe"):
            if k in g.index:
                r = g.loc[k]
                nd = 2 if k == "chrf" else 3
                star = "*" if r.q_sign < 0.05 else ""
                row[ML[k].split(" (")[0].replace("reference-based", "ref").replace("AfriCOMET-QE", "AfriC-QE").replace("SSA-COMET-MTL", "SSA")] = f"{r.delta:+.{nd}f} / {pct(r.pref, 0)}{star}"
            else:
                row[ML[k].split(" (")[0].replace("reference-based", "ref").replace("AfriCOMET-QE", "AfriC-QE").replace("SSA-COMET-MTL", "SSA")] = "-"
        row["fin SFT/RL %"] = f"{pct(g.loc['fin', 'mean_a'], 0)}/{pct(g.loc['fin', 'mean_b'], 0)}"
        row["flag"] = "QE up, ref not all up" if (iso in fl.index and isinstance(fl.loc[iso, "flag"], str)) else ""
        rows.append(row)
    pl = pd.DataFrame(rows)
    P(md(pl))
    P("Cell = delta (RL - SFT) / RL-preferred % of the non-tied sentences; `*` = sign test significant after Benjamini-Hochberg across languages (q < 0.05). chrF++ on all rows; AfriCOMET / SSA on the sampled rows (see text).\n")
    # surface
    P("## T5. Failure modes and language identification (`no_pair`, macro over languages)\n")
    rows = []
    for s in ("all_langs", "group:qe_validated", "group:blend", "group:consensus_only", "group:sft_only"):
        row = {"scope": s}
        for k, lab in (("fin", "finished"), ("loop", "loop (guards)"), ("rep3", "word-3-gram repetition"), ("lid", "GlotLID right language"), ("lid_sib", "GlotLID (sibling-tolerant)"), ("lratio", "length ratio hyp/ref")):
            r = m[(m.subset == "no_pair") & (m.b == "ALL") & (m.scope == s) & (m.metric == k)]
            if len(r):
                r = r.iloc[0]
                row[lab] = f"{r.mean_a:.2f} -> {r.mean_b:.2f}" if k == "lratio" else f"{pct(r.mean_a)} -> {pct(r.mean_b)} ({100 * r.delta:+.1f} [{100 * r.delta_lo:+.1f}, {100 * r.delta_hi:+.1f}])"
        rows.append(row)
    P(md(pd.DataFrame(rows)))
    # agreement
    ag = rd("main", "agreement.csv")
    ag = ag[ag.subset == "no_pair"]
    P("## T6. Agreement between metrics on the sentence-level winner (`no_pair`, sentences scored by all four neural metrics)\n")
    names = {"chrf_sub": "chrF++", "afri_ref": "AfriC-ref", "ssa_ref": "SSA-ref", "afri_qe": "AfriC-QE", "ssa_qe": "SSA-QE"}
    rows = []
    for _, r in ag[~ag.metric_1.astype(str).str.startswith("ens")].iterrows():
        rows.append({"pair": f"{names[r.metric_1]} vs {names[r.metric_2]}", "sentences both call a winner": int(r.n_both_nontie), "same winner %": pct(r.agree_nontie),
                     "same 3-class label %": pct(r.agree_3class), "Cohen kappa (3 class)": f"{r.kappa_3class:.2f}", "Spearman of the deltas": f"{r.spearman_delta:.2f}"})
    P(md(pd.DataFrame(rows)))
    e = ag[ag.metric_1.astype(str).str.startswith("ens_qe")].iloc[0]
    P(f"Sentences where RL wins on BOTH QE metrics ({int(e.n_both_nontie)}): the majority of the three reference-based metrics prefers RL in {pct(e.agree_nontie)}%, is neutral in {pct(e.agree_3class)}%, prefers SFT in {pct(e.kappa_3class)}%.\n")
    ab = rd("main", "agreement_by_group.csv")
    ab = ab[ab.subset == "no_pair"]
    P("Agreement of chrF++ with each neural metric by training group (same winner %, sentences where both call a winner):\n")
    P(md(ab.assign(**{"same winner %": ab.agree_nontie_with_chrf.map(pct)})[["group", "metric_2", "n_both_nontie", "same winner %"]]))
    # thresholds
    P("## T7. Sensitivity to the tie threshold (`no_pair`, all sentences of the metric, pooled)\n")
    th = rd("main", "threshold_sensitivity.csv")
    th = th[th.subset == "no_pair"]
    P(md(th.assign(win=th.win.map(pct), tie=th.tie.map(pct), loss=th.loss.map(pct), pref=th.pref.map(pct), metric=th.metric.map(lambda k: ML[k]))[["metric", "threshold", "n", "win", "tie", "loss", "pref"]]))
    # 320
    P("## T8. FLORES+ at the 320-token budget (`no_pair`; same sentences, macro over 45 languages)\n")
    m3 = rd("max320", "macro.csv")
    rows = []
    for sub in ("no_pair", "clean", "all"):
        for k, lab in (("chrf", "chrF++"), ("fin", "finished"), ("loop", "loop"), ("lid", "GlotLID"), ("lratio", "length ratio")):
            r = m3[(m3.subset == sub) & (m3.b == "flores_plus") & (m3.scope == "all_langs") & (m3.metric == k)]
            if len(r):
                r = r.iloc[0]
                sc = 1 if k in ("chrf", "lratio") else 100
                rows.append({"subset": sub, "metric": lab, "SFT": f"{sc * r.mean_a:.2f}", "RL": f"{sc * r.mean_b:.2f}", "delta [95% CI]": ci_fmt(sc * r.delta, sc * r.delta_lo, sc * r.delta_hi),
                             "win/tie/loss % (macro)": f"{pct(r.macro_win)} / {pct(r.macro_tie)} / {pct(r.macro_loss)}" if k == "chrf" else "", "RL preferred % (micro)": pct(r.micro_pref) if k == "chrf" else ""})
    P(md(pd.DataFrame(rows)))
    # 768 FLORES for comparison
    P("## T9. FLORES+ at the 768-token budget (`no_pair`; headline of the R5 report)\n")
    rows = []
    for sub in ("no_pair", "clean", "all"):
        for k, lab in (("chrf", "chrF++"), ("fin", "finished"), ("loop", "loop"), ("lid", "GlotLID"), ("lratio", "length ratio")):
            r = m[(m.subset == sub) & (m.b == "flores_plus") & (m.scope == "all_langs") & (m.metric == k)]
            if len(r):
                r = r.iloc[0]
                sc = 1 if k in ("chrf", "lratio") else 100
                rows.append({"subset": sub, "metric": lab, "SFT": f"{sc * r.mean_a:.2f}", "RL": f"{sc * r.mean_b:.2f}", "delta [95% CI]": ci_fmt(sc * r.delta, sc * r.delta_lo, sc * r.delta_hi),
                             "win/tie/loss % (macro)": f"{pct(r.macro_win)} / {pct(r.macro_tie)} / {pct(r.macro_loss)}" if k == "chrf" else "", "RL preferred % (micro)": pct(r.micro_pref) if k == "chrf" else ""})
    P(md(pd.DataFrame(rows)))
    # R5 cross-check
    P("## T10. Reproduction check: corpus-level chrF++ per unit against the R5 numbers (`no_pair`)\n")
    cc = rd("main", "corpus_chrf_units.csv")
    cc = cc[cc["subset"] == "no_pair"]
    rows = []
    r5 = pd.concat([pd.read_csv(os.path.join(R5, "bench_metrics_sft.csv")), pd.read_csv(os.path.join(R5, "bench_metrics_rl.csv"))])
    r5 = r5[r5["subset"] == "no_pair"]
    for b in ["flores_plus", "ntrex", "mafand", "smol_sent", "ibom_mt", "flores_moz", "salt", "glot_story"]:
        c = cc[cc.b == b]
        a5 = r5[(r5.benchmark == b) & (r5.system == "sft")].set_index("iso").chrf
        b5 = r5[(r5.benchmark == b) & (r5.system == "rl")].set_index("iso").chrf
        j = c.set_index("iso")
        both = j.index.intersection(a5.index).intersection(b5.index)
        rows.append({"benchmark": BL[b], "langs": len(both), "SFT here": f"{j.loc[both, 'chrf_a'].mean():.2f}", "SFT R5": f"{a5[both].mean():.2f}", "RL here": f"{j.loc[both, 'chrf_b'].mean():.2f}",
                     "RL R5": f"{b5[both].mean():.2f}", "max abs diff per language": f"{max((j.loc[both, 'chrf_a'] - a5[both]).abs().max(), (j.loc[both, 'chrf_b'] - b5[both]).abs().max()):.3f}"})
    P(md(pd.DataFrame(rows)))
    # robustness
    rb = rd("main", "robustness_no_loop.csv")
    P("## T13. Robustness: the same comparison without the sentences on which either model loops / does not finish (`no_pair`)\n")
    rows = []
    for _, r in rb.iterrows():
        nd = 2 if r.metric.startswith("chrf") else 3
        rows.append({"sentences": r.subset, "metric": ML[r.metric], "n": int(r.n), "mean delta (micro)": f"{r.delta_micro:+.{nd}f}", "macro delta over languages": f"{r.delta_macro_lang:+.{nd}f}",
                     "win / tie / loss %": f"{pct(r.win)} / {pct(r.tie)} / {pct(r.loss)}", "RL preferred %": pct(r.pref)})
    P(md(pd.DataFrame(rows)))
    # long documents
    for sub, title in (("longdoc_docs", "T11. Long input: whole documents (R6, sentence-by-sentence decoding of both models, clean documents)"),
                       ("longdoc_segments", "T12. Long input: aligned sentences inside the documents")):
        if not os.path.isdir(os.path.join(D, sub)):
            continue
        ml = rd(sub, "macro.csv")
        P(f"## {title}\n")
        bins = [b for b in ["core_b64", "core_b256", "core_b512", "core_b1024", "core_b2048", "core_b4096", "human_sm", "human_st512", "human_st1024", "human_st2048"] if b in set(ml.b)]
        rows = []
        ks = ("chrf", "fin", "loop") if sub == "longdoc_docs" else ("chrf", "afri_ref", "ssa_ref", "afri_qe", "ssa_qe", "loop")
        for b in bins:
            for k in ks:
                r = ml[(ml.subset == "all") & (ml.b == b) & (ml.scope == "all_langs") & (ml.metric == k)]
                if not len(r):
                    continue
                r = r.iloc[0]
                nd = 2 if k == "chrf" else (1 if k in ("fin", "loop") else 3)
                sc = 100 if k in ("fin", "loop") else 1
                rows.append({"bin": b, "metric": ML.get(k, {"fin": "finished %", "loop": "loop %"}.get(k, k)), "langs": int(r.n_langs), "units": int(r.n_sent), "SFT": f"{sc * r.mean_a:.{nd}f}", "RL": f"{sc * r.mean_b:.{nd}f}",
                             "delta [95% CI]": ci_fmt(sc * r.delta, sc * r.delta_lo, sc * r.delta_hi, nd), "win/tie/loss % (micro)": f"{pct(r.micro_win, 0)} / {pct(r.micro_tie, 0)} / {pct(r.micro_loss, 0)}",
                             "RL preferred % [CI]": f"{pct(r.micro_pref, 0)} [{pct(r.micro_pref_lo, 0)}, {pct(r.micro_pref_hi, 0)}]" if pd.notna(r.micro_pref) else ""})
        P(md(pd.DataFrame(rows)))
    with open(os.path.join(D, "tables.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", os.path.join(D, "tables.md"))


if __name__ == "__main__":
    main()

"""Tables and heat-maps for the inter-African data report (D-46) from the small outputs of the builders (numpy + json only, runs on the laptop).

    python scripts/afri2afri_report_tables.py --tensor pair_count_tensor.npy [--direct direct_pair_counts.json] [--catalog catalog_pairs.json] \
        [--final final_pair_counts.json] --out-dir reports/afri2afri_2026-10-20

Writes `<name>.csv` (the 77 x 77 matrix of ordered counts, rows = source, columns = target) and `heatmaps.md` (one character per cell: `.` 0, `1` 1-99, `2` 100-999,
`3` 1k-9,999, `4` 10k-99,999, `5` >= 100k) for every matrix, plus `thin_directions.md` (directions below 1,000 pairs and what fills them).
"""

from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from gemma_mt.languages import ALL_ISOS  # noqa: E402

SFT77 = [i for i in ALL_ISOS if i not in ("nde", "fat", "knc", "gaa", "men", "luy", "tzm", "ful")]
IDS = [ALL_ISOS.index(i) for i in SFT77]


def bucket(v: int) -> str:
    return "." if v <= 0 else "1" if v < 100 else "2" if v < 1000 else "3" if v < 10_000 else "4" if v < 100_000 else "5"


def heatmap(m: np.ndarray, title: str) -> str:
    n = len(SFT77)
    lines = [f"### {title}", "", "```", "           " + "".join(str((j + 1) // 10) for j in range(n)), "src \\ tgt  " + "".join(str((j + 1) % 10) for j in range(n))]
    for i, l in enumerate(SFT77):
        lines.append(f"{l:3s} {i + 1:>2d}     " + "".join(bucket(int(m[i, j])) if i != j else "-" for j in range(n)))
    lines += ["```", "", "Column number = row number; order: " + " ".join(f"{j + 1}={l}" for j, l in enumerate(SFT77)), ""]
    return "\n".join(lines)


def write_csv(path: str, m: np.ndarray) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("src," + ",".join(SFT77) + "\n")
        for i, l in enumerate(SFT77):
            f.write(l + "," + ",".join(str(int(m[i, j])) for j in range(len(SFT77))) + "\n")


def summary(m: np.ndarray) -> dict:
    off = ~np.eye(len(SFT77), dtype=bool)
    v = m[off]
    return {"directions": int(v.size), "ge1": int((v >= 1).sum()), "ge100": int((v >= 100).sum()), "ge1k": int((v >= 1000).sum()), "ge10k": int((v >= 10_000).sum()),
            "ge100k": int((v >= 100_000).sum()), "total": int(v.sum())}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tensor", required=True)
    ap.add_argument("--direct", default=None)
    ap.add_argument("--catalog", default=None)
    ap.add_argument("--final", default=None, help="json {'src>tgt': pairs} of the built dataset (ordered directions)")
    ap.add_argument("--out-dir", required=True)
    a = ap.parse_args(argv)
    os.makedirs(a.out_dir, exist_ok=True)
    c = np.load(a.tensor)
    sub = lambda t: c[t][np.ix_(IDS, IDS)] if isinstance(t, int) else c[list(t)].sum(0)[np.ix_(IDS, IDS)]
    mats = {"pivot_en_all": sub((0, 1, 2, 3)), "pivot_en_without_religious_or_synthetic": sub((1, 3)), "pivot_en_human_curated_only": sub(3)}
    if a.direct:
        d = json.load(open(a.direct))
        m = np.zeros((len(SFT77), len(SFT77)), np.int64)
        for k, v in d["direct_pairs"].items():
            x, y = k.split("-")
            if x in SFT77 and y in SFT77:
                m[SFT77.index(x), SFT77.index(y)] += v
                m[SFT77.index(y), SFT77.index(x)] += v
        mats["direct_rows_of_the_sft_corpus"] = m
    if a.catalog:
        d = json.load(open(a.catalog))
        m = np.zeros((len(SFT77), len(SFT77)), np.int64)
        for k, v in d["pairs"].items():
            x, y = k.split("-")
            if x in SFT77 and y in SFT77:
                m[SFT77.index(x), SFT77.index(y)] += v
                m[SFT77.index(y), SFT77.index(x)] += v
        mats["NOT_HELD_nllb_mined_michsethowusu_catalogue"] = m
    if a.final:
        d = json.load(open(a.final))
        m = np.zeros((len(SFT77), len(SFT77)), np.int64)
        for k, v in d.items():
            x, y = k.split(">")
            if x in SFT77 and y in SFT77:
                m[SFT77.index(x), SFT77.index(y)] += v
        mats["built_dataset_pairs"] = m
    out = ["# Pair-coverage matrices (generated by scripts/afri2afri_report_tables.py)", "",
           "Legend: `.` 0 | `1` 1-99 | `2` 100-999 | `3` 1,000-9,999 | `4` 10,000-99,999 | `5` >= 100,000 ordered pairs. `-` = same language.", ""]
    summ = {}
    for name, m in mats.items():
        write_csv(os.path.join(a.out_dir, f"{name}.csv"), m)
        summ[name] = summary(m)
        out.append(heatmap(m, f"{name}  (ordered directions >=1: {summ[name]['ge1']}, >=1k: {summ[name]['ge1k']}, >=10k: {summ[name]['ge10k']}, total {summ[name]['total']:,})"))
    open(os.path.join(a.out_dir, "heatmaps.md"), "w", encoding="utf-8").write("\n".join(out))
    json.dump(summ, open(os.path.join(a.out_dir, "matrix_summary.json"), "w"), indent=1)
    # thin directions of the best available matrix (built dataset if given, else pivot + direct)
    base = mats.get("built_dataset_pairs", mats["pivot_en_all"] + mats.get("direct_rows_of_the_sft_corpus", 0))
    pot = mats.get("NOT_HELD_nllb_mined_michsethowusu_catalogue")
    rows = [(SFT77[i], SFT77[j], int(base[i, j]), int(pot[i, j]) if pot is not None else 0) for i in range(len(SFT77)) for j in range(len(SFT77)) if i != j and base[i, j] < 1000]
    lang_thin = {}
    for s, t, n, p in rows:
        lang_thin[s] = lang_thin.get(s, 0) + 1
    lines = ["# Thin directions (< 1,000 pairs in the best matrix)", "", f"{len(rows)} of {len(SFT77) * (len(SFT77) - 1)} ordered directions.", "",
             "| language | thin directions as SOURCE (of 76) |", "|---|---:|"]
    for l, n in sorted(lang_thin.items(), key=lambda kv: -kv[1])[:40]:
        lines.append(f"| {l} | {n} |")
    open(os.path.join(a.out_dir, "thin_directions.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    json.dump([r for r in rows], open(os.path.join(a.out_dir, "thin_directions.json"), "w"))
    print(json.dumps(summ, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""D-68: the Gemini-generated Urhobo silver set as a CHECK of the urh detectors (never as a source of thresholds, a stop-word profile or a loanword list).

Owner / coordinator rules (2026-10-22): the 230 pairs were generated by Gemini, not written or verified by a native speaker, with a templated look and an unknown error rate. So this script
  (a) compares the flag rates of the v3 urh detectors on the silver set (A: 60 short phrases, B-F: 170 sentences, reported separately) with their leave-one-set-out flag rates on the JW / pivot text
      -> a large disagreement means one of the two is unreliable; reported, not resolved;
  (b) compares coarse, domain-robust statistics (length ratio in words and characters, digit and capitalised-name retention, punctuation share, tokens shared with English, type / token ratio);
  (c) measures the vocabulary overlap with the JW / SFT pool (share of word types and tokens unseen in the urh text of our SFT corpus) and the share of the templated connectors;
and fits nothing.
    python scripts/urh_silver_check.py --cal anchors_v3.json --cal-v2 anchors_v2.json --silver urhobo_gemini_silver_2026-10-22.jsonl --mix /workspace/jobs/r4/mix_v1 \
        --tokenizer /workspace/sft_build/runs/final_1433/tokenizer.json --corpus /workspace/jobs/b3/corpus --out urh_silver_check.md
"""

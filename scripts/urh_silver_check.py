CONNECTORS = ["khwọndeniefẹ", "ọtiọyena", "ofori", "nneyi", "dẹndẹn"]


def flag_rates(blocks, units):
    """Flag rates of the blocks as fitted, `usable` ignored (a detector that is switched off in the reward is still measured here, for the comparison)."""
    return C3.fp_report({k: dict(v, usable=True) for k, v in blocks.items() if v}, units)


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return max(0.0, c - h), min(1.0, c + h)


def coarse(units):
    wr, cr, dig, nm, pun, shared, ttr, wl = [], [], [], [], [], [], [], []
    for u in units:
        sw, ow = u["src"].split(), u["ref"].split()
        if not sw or not ow:
            continue
        wr.append(len(ow) / len(sw))
        cr.append(len(u["ref"]) / max(len(u["src"]), 1))
        ec = A1.entity_counts(u["src"], u["ref"])
        if ec.n_num:
            dig.append(ec.recall_num)
        if ec.n_name:
            nm.append(ec.recall_name)
        pun.append(sum(1 for c in u["ref"] if not c.isalnum() and not c.isspace()) / max(len(u["ref"]), 1))
        st, ot = set(T.out_tokens(u["src"])), T.out_tokens(u["ref"])
        ot_alpha = [t for t in ot if not t.isdigit()]
        shared.append(sum(1 for t in ot_alpha if t in st) / max(len(ot_alpha), 1))
        ttr.append(len(set(ot)) / max(len(ot), 1))
        wl.append(np.mean([len(t) for t in ot]) if ot else 0)
    f = lambda v: (float(np.mean(v)), float(np.median(v)), len(v)) if v else (None, None, 0)
    return {"words ref/en": f(wr), "chars ref/en": f(cr), "numbers kept": f(dig), "capitalised names kept": f(nm), "punctuation share of chars": f(pun), "tokens shared with the English source": f(shared),
            "type/token ratio": f(ttr), "mean token length": f(wl)}


def sft_vocab(mix, tokenizer, corpus, iso="urh"):
    """Word types / token counts of the urh TARGET text of our SFT corpus (R4 mixture, decoded) + R3's pivot corpus without its held-out rows."""
    cnt: collections.Counter = collections.Counter()
    if mix:
        from tokenizers import Tokenizer

        tk = Tokenizer.from_file(tokenizer)
        d = mix.rstrip("/") + "/train/"
        tok = np.memmap(d + "tokens.u32.bin", dtype=np.uint32, mode="r")
        off, pl, sl, iid, direction = (np.load(d + f + ".npy") for f in ("sample_offset", "prompt_len", "sample_len", "iso_id", "direction"))
        tab = json.load(open(mix.rstrip("/") + "/meta.json"))["iso_table"]
        k = tab.index(iso) if iso in tab else -1
        for i in np.nonzero(iid == k)[0]:
            if direction[i] == 0:
                cnt.update(T.out_tokens(tk.decode(tok[off[i] + pl[i]: off[i] + sl[i]].tolist())))
    if corpus:
        import pyarrow.parquet as pq

        fn = os.path.join(corpus, iso + ".parquet")
        if os.path.exists(fn):
            t = pq.read_table(fn, columns=["x", "held"]).to_pydict()
            for x, h in zip(t["x"], t["held"]):
                if not h:
                    cnt.update(T.out_tokens(x))
    return cnt


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cal", required=True)
    ap.add_argument("--cal-v2", default=None)
    ap.add_argument("--silver", required=True)
    ap.add_argument("--mix", default=None)
    ap.add_argument("--tokenizer", default=None)
    ap.add_argument("--corpus", default=None)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    cal = json.load(open(a.cal, encoding="utf-8"))["languages"]["urh"]
    blocks = {k: cal.get(k) for k in ("copy", "func", "pad")}
    silver = [json.loads(l) for l in open(a.silver, encoding="utf-8")]
    sil = {"A (60 short phrases)": [{"src": r["english"], "ref": r["urhobo"], "set": "silver"} for r in silver if r["set"] == "A"],
           "B-F (170 sentences)": [{"src": r["english"], "ref": r["urhobo"], "set": "silver"} for r in silver if r["set"] != "A"]}
    L = []
    P = L.append
    P("# Gemini-Urhobo silver set as a check of the urh detectors (D-68)\n")
    P("The set was GENERATED BY GEMINI (not native-written, not verified, unknown error rate). Nothing below is fitted on it.\n")
    # (a) flag rates
    P("## (a) detector flag rates: silver vs JW / pivot text\n")
    P("Cells: share of units with a deficit > 0 (graded penalty) / >= 0.9 (gate level), [95 % Wilson interval], n judged. `JW held-out` = leave-one-set-out numbers of the v3 fit "
      "(thresholds from the other JW / pivot sets, rates on the held-out set; sentence + 10-sentence windows).\n")
    P("| detector | usable (v3) | silver A | silver B-F | JW leave-one-set-out (per set) |\n|---|---|---|---|---|")
    rates = {n: flag_rates(blocks, us) for n, us in sil.items()}
    for det in ("copy", "func", "pad"):
        b = blocks.get(det)
        cells = []
        for n in sil:
            r = rates[n].get(det)
            if not r:
                cells.append("-")
                continue
            lo, hi = wilson(round(r["fp"] * r["n"]), r["n"])
            cells.append(f"{r['fp']:.3f} / {r['sat']:.3f} [{lo:.3f}, {hi:.3f}] n={r['n']}")
        per = ((b or {}).get("lodo_per_set") or {})
        jw = "; ".join(f"{s}: {v['fp']:.3f} / {v['sat']:.3f} (n={v['n']})" for s, v in per.items()) or "-"
        P(f"| {det} | {None if not b else b.get('usable')} | {cells[0]} | {cells[1]} | {jw} |")
    if a.cal_v2:
        v2 = json.load(open(a.cal_v2, encoding="utf-8"))["languages"]["urh"]
        b2 = {k: v2.get(k) for k in ("copy", "func", "pad")}
        P("\nFor comparison, the v2 `pivot_held` blocks of urh (what the live run used) on the same silver text (the v2 pad block needs the bigram table, not loaded here: padding shows the type / token part only):\n")
        P("| detector | silver A | silver B-F |\n|---|---|---|")
        r2 = {n: flag_rates(b2, us) for n, us in sil.items()}
        for det in ("copy", "func", "pad"):
            P(f"| {det} (v2) | " + " | ".join(("-" if not r2[n].get(det) else f"{r2[n][det]['fp']:.3f} / {r2[n][det]['sat']:.3f} (n={r2[n][det]['n']})") for n in sil) + " |")
    # (b) coarse
    P("\n## (b) coarse statistics (mean / median / n): silver vs JW pivot sentences vs JW windows\n")
    sets = D.load_sets("urh")
    jw_sent = sets.get("pivot_held", [])
    jw_win = sets.get("r15_val", [])
    cs = {"silver A": coarse(sil["A (60 short phrases)"]), "silver B-F": coarse(sil["B-F (170 sentences)"]), "JW pivot sentences": coarse(jw_sent), "JW val windows": coarse(jw_win)}
    P("| statistic | " + " | ".join(cs) + " |\n|---|" + "---|" * len(cs))
    for k in cs["silver A"]:
        P(f"| {k} | " + " | ".join(("-" if cs[n][k][0] is None else f"{cs[n][k][0]:.2f} / {cs[n][k][1]:.2f} (n={cs[n][k][2]})") for n in cs) + " |")
    # (c) vocabulary
    P("\n## (c) vocabulary overlap with the urh text of our SFT corpus (bias indicator)\n")
    voc = sft_vocab(a.mix, a.tokenizer, a.corpus)
    P(f"SFT-side urh word types: {len(voc)}, tokens: {sum(voc.values())} (R4 mixture targets, decoded, + R3 pivot rows without the held-out ones).\n")
    P("| text | tokens | types | types unseen in the SFT text | tokens unseen | top-5 types' share of tokens |\n|---|---|---|---|---|---|")
    texts = {"silver A": [u["ref"] for u in sil["A (60 short phrases)"]], "silver B-F": [u["ref"] for u in sil["B-F (170 sentences)"]], "JW pivot held-out sentences": [u["ref"] for u in jw_sent],
             "JW val windows (held out)": [u["ref"] for u in jw_win]}
    ctr = {}
    for n, ts in texts.items():
        c = collections.Counter(t for x in ts for t in T.out_tokens(x))
        ctr[n] = c
        tot = sum(c.values())
        un_t = [w for w in c if w not in voc]
        un_k = sum(c[w] for w in un_t)
        top5 = sum(v for _, v in c.most_common(5)) / max(tot, 1)
        P(f"| {n} | {tot} | {len(c)} | {len(un_t) / max(len(c), 1):.3f} | {un_k / max(tot, 1):.3f} | {top5:.3f} |")
    P("\nTemplated connectors, occurrences per 1,000 tokens:\n")
    P("| word | " + " | ".join(texts) + " |\n|---|" + "---|" * len(texts))
    for w in CONNECTORS:
        wf = T.out_tokens(w)[0]
        P(f"| {w} | " + " | ".join(f"{1000 * ctr[n].get(wf, 0) / max(sum(ctr[n].values()), 1):.1f}" for n in texts) + " |")
    P("\nMost frequent silver B-F types: " + ", ".join(f"{w} ({c})" for w, c in ctr["silver B-F"].most_common(15)))
    open(a.out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

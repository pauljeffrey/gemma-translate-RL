"""D-68: re-run the anchors calibration of ONE language with a NEW native-verified human benchmark (jsonl rows {english, reference}; for Urhobo also accepted: {english, urhobo}).

    python scripts/refit_urh_bench.py --iso urh --bench urhobo_native_100.jsonl --cal calibration/anchors_v3.json --funcwords calibration/funcwords_v1.json \
        --out calibration/anchors_v3_urh_refit.json --dev-out urh_dev.jsonl [--bigrams calibration/anchors_v2_bigrams.npz]

(a) measures the false-positive share of every detector of the current entry on the benchmark, with the exact 95 % Clopper-Pearson upper bound -- and says what n can resolve (0 of 100 only proves
    "<= 3 %", 1 of 100 "<= 4.7 %"; a rate of 1-2 % cannot be measured with 100 sentences);
(b) refits the language with the benchmark as one more out-of-domain SET (same recipe, anchors_calibrate_v3.build_language_v3): the benchmark can only LOOSEN a threshold (the tail thresholds are the
    loosest over the sets; the copy threshold is kept at max(old, new)); usable / gate_ok then come from the leave-one-set-out numbers with the benchmark held out;
(c) writes the dev chrF++ harness file (rows english, reference, iso, benchmark, id) and prints the `benchmark_aux` entry for the trainer yaml.
A set generated by an LLM (the Gemini Urhobo silver set) must NOT be given here: use scripts/urh_silver_check.py for that.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_anchors_v3_calibration as B  # noqa: E402
from gemma_mt.rl import anchors_calibrate_v3 as C3  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--iso", default="urh")
    ap.add_argument("--bench", required=True)
    ap.add_argument("--cal", required=True)
    ap.add_argument("--funcwords", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--dev-out", default=None)
    ap.add_argument("--dev-name", default=None)
    ap.add_argument("--bigrams", default=None)
    ap.add_argument("--human", default="/workspace/jobs/b2/human_units.jsonl")
    a = ap.parse_args()
    cal = json.load(open(a.cal, encoding="utf-8"))
    fwd = json.load(open(a.funcwords, encoding="utf-8"))
    bench = B.load_bench(a.bench)
    n = len(bench)
    print(f"[refit] {a.iso}: {n} benchmark pairs from {a.bench}")
    if n < 20:
        sys.exit("[refit] fewer than 20 pairs: nothing can be measured")
    # (a) FP of the CURRENT entry
    cur = cal["languages"].get(a.iso) or {}
    blocks = {k: cur.get(k) for k in ("copy", "func", "pad") if cur.get(k)}
    rep = C3.fp_report({k: dict(v, usable=True) for k, v in blocks.items()}, bench)
    print("[refit] (a) false positives of the current entry on the benchmark (graded = deficit > 0; gate = deficit >= 0.9):")
    for det, r in rep.items():
        k, ks = int(round(r["fp"] * r["n"])), int(round(r["sat"] * r["n"]))
        print(f"        {det:5s} usable={blocks[det].get('usable')}  graded {k}/{r['n']} = {r['fp']:.3f} (95 % upper bound {C3.binom_upper(k, r['n']):.3f})   gate {ks}/{r['n']} (upper {C3.binom_upper(ks, r['n']):.3f})")
    print(f"        n = {n}: zero flags prove only 'FP <= {C3.binom_upper(0, n):.3f}' at 95 %; rates of 1-3 % cannot be told apart from 0 with this set.")
    # (b) refit with the benchmark as one more set
    new, report = B.build(cal, fwd, [a.iso], {a.iso: bench}, human=a.human)
    e_old, e_new = cur, new["languages"][a.iso]
    for det in ("copy", "func", "pad"):
        o, nw = e_old.get(det), e_new.get(det)
        if not o or not nw:
            continue
        if det == "copy":                                   # never tighten from a small set
            for t in ("t_w", "t_c"):
                nw[t] = max(nw[t], o[t])
        print(f"[refit] (b) {det}: usable {o.get('usable')} -> {nw.get('usable')}, gate_ok {o.get('gate_ok')} -> {nw.get('gate_ok')} ({nw.get('usable_reason')})")
        for k in ("t_fw", "t_ttr", "t_w"):
            if k in o and k in nw:
                print(f"        {k}: {o[k]} -> {nw[k]}")
    new["languages"][a.iso]["v3"]["bench"] = {"file": os.path.basename(a.bench), "n": n}
    json.dump(new, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("[refit] wrote", a.out)
    # (c) dev harness
    if a.dev_out:
        name = a.dev_name or f"{a.iso}_dev"
        with open(a.dev_out, "w", encoding="utf-8") as f:
            for i, u in enumerate(bench):
                f.write(json.dumps({"english": u["src"], "reference": u["ref"], "iso": a.iso, "benchmark": name, "id": f"{name}_{i}"}, ensure_ascii=False) + "\n")
        print(f"[refit] (c) dev file {a.dev_out} ({n} rows). Trainer yaml `benchmark_aux` entry (logged as bench_aux/{name}/chrf/{a.iso}, monitor only):")
        print(f"  - {{name: {name}, path: {os.path.abspath(a.dev_out)}, per_language: {min(n, 100)}, max_new_tokens: 256, batch_size: 64}}")


if __name__ == "__main__":
    main()

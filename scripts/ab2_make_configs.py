"""AB2: write the RL arm configs (F, W) and the SFT configs (weak SFT, S1, S1P) of the cheap ablation.

    python scripts/ab2_make_configs.py --template configs/rl_ablation_full.yaml --sft-template configs/ab1_sft_weak.yaml --out-dir configs [--steps 49] [--s1-steps 420]

RL (rl_ab2_full.yaml, rl_ab2_weak.yaml): AB1's arm config (= the phase-2c reward / calibration v7 / GlotLID guard / consensus / length-ratio-diacritic terms, group 16, std-normalised advantage,
lr 2e-6, k3c KL 0.05 + guard, fresh optimizer, seed 1234) with only these changes, all identical for the two arms (asserted: the arms differ in model_name / out_dir / run_name ONLY):
  * 49 steps x 64 b64 prompts x group 16 = 50,176 completions (curriculum b64 only, max_new_tokens 384, vllm_max_model_len 2048);
  * prompts_path = data/rl_prompts_ab2 (yor kin orm lin, b64, decontaminated), language_weights {} (AB1 / 2c gave yor and orm x2.5: with four languages that would be an unequal budget);
  * warmup_steps 5 (10 in 2c: of 49 steps that would be 20% of the run at reduced LR); lr stays 2e-6;
  * dev evaluation every 10 steps on ALL clean dev rows of the chosen languages (yor 610, kin 526, orm 70; lin has no dev rows in bench_dev_clean), save_every 25, snapshot at the last step.
SFT: ab2_sft_weak.yaml = AB1's weak SFT (AdamW lr 5e-5 cosine to 5e-6 over 3,500 steps, language_alpha 0.5, the first 3,500 steps of the real stage A) with AB2 paths;
ab2_sft_s1.yaml = continued SFT from W on the real stage-A packs of steps 3,501.. (schedule_start_step 3500, max_steps N), fresh AdamW, warm-up 20, LR constant at W's end value 5e-6 for 80% of the
steps and a linear anneal to 5e-7; ab2_sft_s1pair.yaml = the same recipe on the pair-matched set (3,136 short samples of the chosen languages, 8 packs per step).
"""
from __future__ import annotations

import argparse
import os
import re
import sys


def set_line(text: str, key: str, value: str, comment: str = "") -> str:
    pat = re.compile(rf"^{re.escape(key)}:.*$", re.M)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"key {key!r}: expected exactly one top-level line, found {len(pat.findall(text))}")
    return pat.sub(lambda m: f"{key}: {value}" + (f"  # {comment}" if comment else ""), text)


def set_block(text: str, key: str, entries) -> str:
    pat = re.compile(rf"^{re.escape(key)}:[^\n]*\n(?:[ \t]+[^\n]*\n)+", re.M)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"block {key!r}: expected exactly one, found {len(pat.findall(text))}")
    body = "".join(f"  {k}: {v}\n" for k, v in entries)
    return pat.sub(lambda m: f"{key}:\n{body}", text)


def build_rl(template: str, model: str, run_name: str, a) -> str:
    t = open(template, encoding="utf-8").read().replace("/workspace/jobs/ab1/", f"{a.ab}/")
    t = re.sub(r"^# AB1 ablation arm.*?\n(# .*\n){2}", "", t, count=1, flags=re.M)
    t = set_line(t, "model_name", model, "AB2: START checkpoint of the arm; also the frozen KL reference; FRESH optimizer")
    t = set_line(t, "prompts_path", f"{a.ab}/data/rl_prompts_ab2", "AB2: yor kin orm lin, b64 windows, decontaminated (scripts/ab2_make_prompts.py); identical for both arms")
    t = set_line(t, "out_dir", f"{a.ab}/runs/{run_name}")
    ps = a.prompts_per_step
    t = set_line(t, "steps", str(a.steps), f"AB2: {a.steps} b64 steps x {ps} prompts x group 16 = {a.steps * ps * 16:,} completions per arm")
    t = set_line(t, "prompts_per_step", str(ps))
    t = set_line(t, "max_new_tokens", "384")
    t = set_line(t, "max_src_tokens", "256")
    t = set_line(t, "vllm_max_model_len", "2048", "AB2: b64 prompt <= ~150 tokens + 384 new")
    t = set_block(t, "curriculum_steps", [("b64", a.steps)])
    t = set_block(t, "prompts_per_step_by_bin", [("b64", ps)])
    t = set_block(t, "max_new_tokens_by_bin", [("b64", 384)])
    t = set_line(t, "language_weights", "{}", "AB2: uniform over the four languages (2c's x2.5 on yor / orm would make the budget unequal)")
    t = set_line(t, "warmup_steps", str(a.warmup), "AB2: 5 of 49 steps (2c: 10)")
    t = set_line(t, "eval_every", "10")
    t = set_line(t, "benchmark_eval_every", "10")
    t = set_line(t, "benchmark_eval_per_language", "0", "AB2: 0 = ALL clean dev rows of the chosen languages")
    t = set_line(t, "save_every", "25", "AB2: last/ is a symlink into /dev/shm; resumable after a trainer crash")
    t = set_line(t, "hub_repo_id", "null", "AB2: nothing is pushed")
    t = set_line(t, "run_name", run_name)
    t = re.sub(r"^export_steps:.*$", f"export_steps: [{a.steps}]               # AB2: snap_step{a.steps} (bf16 HF dir) = the evaluated model", t, flags=re.M)
    head = (f"# AB2 ablation arm '{run_name}' (cheap RL-vs-SFT-start ablation): generated by scripts/ab2_make_configs.py from AB1's arm config. The two arms differ ONLY in\n"
            f"# model_name / out_dir / run_name. {a.steps} steps x {ps} b64 prompts x group 16 = {a.steps * ps * 16:,} completions, languages yor kin orm lin, lr 2e-6, k3c KL 0.05 + guard, fresh optimizer.\n")
    return head + t


def build_sft(template: str, a, name: str, **kv) -> str:
    t = open(template, encoding="utf-8").read().replace("/workspace/jobs/ab1/", f"{a.ab}/")
    for k, v in kv.items():
        pat = re.compile(rf"^{re.escape(k)}:.*$", re.M)
        if pat.search(t):
            t = pat.sub(lambda m: f"{k}: {v}", t, count=1)
        else:
            t = t.rstrip("\n") + f"\n{k}: {v}\n"
    return f"# AB2 SFT config '{name}' (generated by scripts/ab2_make_configs.py from AB1's weak-SFT config; changed keys: {', '.join(kv)})\n" + t


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", required=True)
    ap.add_argument("--sft-template", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--ab", default="/workspace/jobs/ab2")
    ap.add_argument("--steps", type=int, default=49)
    ap.add_argument("--prompts-per-step", type=int, default=64)
    ap.add_argument("--warmup", type=int, default=5)
    ap.add_argument("--s1-steps", type=int, default=420, help="N SFT steps of S1 (GPU-time matched to one RL arm; rewritten by scripts/ab2_set_n.py from the measured arm time)")
    ap.add_argument("--s1-lr", type=float, default=5e-6, help="W's end LR (5e-5 x min_lr_ratio 0.1)")
    ap.add_argument("--s1-hold", type=float, default=0.8)
    a = ap.parse_args(argv)
    os.makedirs(a.out_dir, exist_ok=True)
    out = {}
    for arm, model, name in (("weak", f"{a.ab}/models/sft_weak", "ab2_weak"), ("full", f"{a.ab}/models/sft_final", "ab2_full")):
        out[arm] = build_rl(a.template, model, name, a)
        open(os.path.join(a.out_dir, f"rl_ab2_{arm}.yaml"), "w", encoding="utf-8").write(out[arm])
    norm = {k: re.sub(r"ab2_(weak|full)", "ARM", v.replace(f"{a.ab}/models/sft_weak", "MODEL").replace(f"{a.ab}/models/sft_final", "MODEL")) for k, v in out.items()}
    if norm["weak"] != norm["full"]:
        raise SystemExit("the two arm configs differ in more than model_name / out_dir / run_name")
    w = f"{a.ab}/models/sft_weak"
    cfg = {
        "ab2_sft_weak.yaml": build_sft(a.sft_template, a, "weak SFT", out_dir=f"{a.ab}/runs/sft_weak", run_name="ab2_sft_weak"),
        "ab2_sft_s1.yaml": build_sft(a.sft_template, a, "S1 (GPU-time matched)", model_name=w, tokenizer_name=w, data_dir=f"{a.ab}/data/packed_s1", out_dir=f"{a.ab}/runs/sft_s1",
                                     run_name="ab2_sft_s1", max_steps=a.s1_steps, schedule_start_step=3500, learning_rate=f"{a.s1_lr:g}", warmup_ratio=0.0, warmup_steps=20,
                                     lr_hold_fraction=a.s1_hold, eval_every=150, save_every=1000000),
        "ab2_sft_s1pair.yaml": build_sft(a.sft_template, a, "S1P (pair-matched)", model_name=w, tokenizer_name=w, data_dir=f"{a.ab}/data/packed_s1_pair", out_dir=f"{a.ab}/runs/sft_s1pair",
                                         run_name="ab2_sft_s1pair", micro_batch_size=8, grad_accum_steps=1, epochs=1.0, max_steps=0, language_alpha="null", learning_rate=f"{a.s1_lr:g}",
                                         warmup_ratio=0.0, warmup_steps=3, lr_hold_fraction=a.s1_hold, eval_every=1000000, save_every=1000000),
    }
    for fn, txt in cfg.items():
        open(os.path.join(a.out_dir, fn), "w", encoding="utf-8").write(txt)
    print("wrote rl_ab2_full.yaml, rl_ab2_weak.yaml (identical except model_name / out_dir / run_name),", ", ".join(cfg))
    return 0


if __name__ == "__main__":
    sys.exit(main())

class H(float):
    """float whose format spec '.Nf' / '+.Nf' rounds half away from zero on the decimal repr (52.05 -> 52.1, -6.55 -> -6.6), as the report does."""

    def __format__(self, spec):
        import re
        from decimal import Decimal, ROUND_HALF_UP
        m = re.match(r"^(\+?)\.(\d+)f$", spec)
        if not m:
            return float.__format__(self, spec)
        v = Decimal(repr(float(self))).quantize(Decimal(1).scaleb(-int(m.group(2))), rounding=ROUND_HALF_UP)
        if v == 0:
            v = abs(v)
        t = format(v, "f")
        return ("+" + t) if (m.group(1) and v >= 0) else t


def fl(x):
    return H(float(x))


def write_md(name, header, rows, align=None):
    align = align or (["l"] + ["r"] * (len(header) - 1))
    sep = "|" + "|".join({"l": ":--", "r": "--:"}[a] for a in align) + "|"
    out = ["| " + " | ".join(header) + " |", sep] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    open(os.path.join(TAB, name + ".md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("table", name, len(rows))


def tex_table(fname, label, caption, colspec, header, rows, midrules=(), star=False, size="small", tabcolsep="3pt"):
    env = "table*" if star else "table"
    L = ["% generated by paper/scripts/make_judge.py from reports/data/judge_j2_2026-10-25/; do not edit by hand",
         BS + "begin{" + env + "}[t]", BS + "centering" + BS + size + BS + "setlength{" + BS + "tabcolsep}{" + tabcolsep + "}",
         BS + "begin{tabular}{" + colspec + "}", BS + "toprule", " & ".join(header) + " " + BS + BS, BS + "midrule"]
    for i, r in enumerate(rows):
        L.append(" & ".join(r) + " " + BS + BS)
        if i in midrules:
            L.append(BS + "midrule")
    L += [BS + "bottomrule", BS + "end{tabular}", BS + "caption{" + caption + "}", BS + "label{" + label + "}", BS + "end{" + env + "}", ""]
    open(os.path.join(SHORT, fname), "w", encoding="utf-8").write("\n".join(L))
    print("short table", fname)



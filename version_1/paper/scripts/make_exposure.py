def check():
    """Abort if a number written into the stage table disagrees with the audit files."""
    assert fl.loc["flores_plus", "exact_pct"] == 95.3 and fl.loc["flores_plus", "pair_pct"] == 4.1
    assert fx["devtest"]["exact"] == 964 and fx["devtest"]["n"] == 1012 and fx["devtest"]["ids_with_pair_in_any_language"] == 933
    assert fx["dev"]["exact"] == 984 and fx["dev"]["n"] == 997 and fx["dev"]["exact_pct"] == 98.7
    pc = fx["devtest"]["pair_langs_counts"]
    assert (pc["hau"], pc["ibo"], pc["yor"], pc["zul"], pc["tsn"], pc["orm"], pc["lug"]) == (842, 559, 355, 36, 30, 24, 2)
    assert round(100 * 842 / 1012) == 83 and round(100 * 559 / 1012) == 55 and round(100 * 355 / 1012) == 35
    assert pool["windows"] == 87498 and pool["windows_with_flores_english"] == 24 and pool["by_iso"]["lug"] == 16
    for b, v in dict(ntrex=39.9, mafand=21.9, smol_sent=91.2, salt=84.4, glot_story=7.2, dev=72.6).items():
        assert fl.loc[b, "exact_pct"] == v, (b, fl.loc[b, "exact_pct"])
    ex = {r["benchmark"]: r for r in rl["distinct"] if r["subset"] == "all"}
    assert ex["flores_plus"]["any_pool_exact"] == 7 and ex["flores_plus"]["distinct_english"] == 1012
    own = [r for r in rl["results"] if r["benchmark"] == "flores_plus" and r["subset"] == "all" and r["scope"] == "same_language_pool" and r["pool"] == "any_pool"][0]
    assert own["exact"] == 21 and own["rows"] == 45540
    cl = [r for r in rl["results"] if r["benchmark"] == "flores_plus" and r["subset"] == "clean" and r["scope"] == "any_language_pool" and r["pool"] == "any_pool"][0]
    assert cl["exact"] == 0 and cl["rows"] == 2160
    mf = [r for r in rl["results"] if r["benchmark"] == "mafand" and r["subset"] == "all" and r["scope"] == "same_language_pool" and r["pool"] == "any_pool"][0]
    assert mf["exact"] == 31 and mf["rows"] == 20008
    print("check: stage-table numbers agree with the audit files")


check()


def md(name, header, rows, align=None):
    a = align or (["--"] + ["--:"] * (len(header) - 1))
    a = [":--" if x == "--" else x for x in a]
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(a) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    open(os.path.join(TAB, name + ".md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("table", name, len(rows))


def tex(fname, label, caption, colspec, header, rows, midrules=(), star=True, size="footnotesize"):
    env = "table*" if star else "table"
    L = ["% generated by paper/scripts/make_exposure.py; do not edit by hand",
         BS + "begin{" + env + "}[t]", BS + "centering" + BS + size + BS + "setlength{" + BS + "tabcolsep}{3pt}",
         BS + "begin{tabular}{" + colspec + "}", BS + "toprule", " & ".join(header) + " " + BS + BS, BS + "midrule"]
    for i, r in enumerate(rows):
        L.append(" & ".join(r) + " " + BS + BS)
        if i in midrules:
            L.append(BS + "midrule")
    L += [BS + "bottomrule", BS + "end{tabular}", BS + "caption{" + caption + "}", BS + "label{" + label + "}", BS + "end{" + env + "}", ""]
    open(os.path.join(SHORT, fname), "w", encoding="utf-8").write("\n".join(L))
    print("short table", fname)


def f1(x):
    return f"{x:.1f}"


def f2(x):
    return f"{x:.2f}"


def sg(x, d=2):
    return f"{x:+.{d}f}"


def tm(s):
    """LaTeX minus signs for the short tables."""
    return s.replace("[-", "[$-$").replace(", -", ", $-$").replace("(-", "($-$") if not s.startswith("-") else "$-$" + tm(s[1:])



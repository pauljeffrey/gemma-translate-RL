# ---------------------------------------------------------------------------------------------- 3. size of the effect and what survives
def size_rows(texmode=False):
    rows = []
    for k, nm in ORDER:
        r = bt.loc[k]
        sa, sc, ra, rc = r["sft_chrf_all"], r["sft_chrf_clean"], r["rl_chrf_all"], r["rl_chrf_clean"]
        gap_s, gap_r = sa - sc, ra - rc
        ci = f"{sg(r['d_chrf_clean'])} [{sg(r['d_chrf_clean_lo'])}, {sg(r['d_chrf_clean_hi'])}]"
        npw = f"{sg(r['d_chrf_no_pair'])}"
        row = [nm, str(int(r["langs_clean"])), f"{int(r['rows_clean']):,} ({r['share_clean_pct']:.1f}%)", f"{f1(sa)} / {f1(sc)}", sg(gap_s, 1),
               f"{f1(ra)} / {f1(rc)}", sg(gap_r, 1), npw, ci]
        rows.append([tm(c) for c in row] if texmode else row)
    return rows


def size_md():
    md("t_exposure_size", ["benchmark", "languages", "`clean` rows", "SFT chrF++ all / clean", "SFT all $-$ clean", "RL chrF++ all / clean",
                           "RL all $-$ clean", "RL $-$ SFT, `no_pair`", "RL $-$ SFT, `clean` [95% CI]"], size_rows(),
       ["--", "--:", "--:", "--:", "--:", "--:", "--:", "--:", "--:"])



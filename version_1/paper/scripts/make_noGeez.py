ci = lambda x: tuple(float(v) for v in np.percentile(x, [2.5, 97.5]))


class Boot:
    """Identical to judge_j2_run3_analyze.Boot (same generator, same order of draws)."""

    def __init__(self, docs_by_lang):
        rng = np.random.default_rng(2026)
        self.docs = {l: sorted(v) for l, v in docs_by_lang.items()}
        self.W = {l: rng.multinomial(len(v), np.full(len(v), 1 / len(v)), size=NB).astype(float) for l, v in self.docs.items()}

    def vec(self, lang, df, col):
        g = df.groupby("doc_id")[col]
        num = g.sum().reindex(self.docs[lang]).fillna(0).to_numpy(float)
        den = g.count().reindex(self.docs[lang]).fillna(0).to_numpy(float)
        return num, den

    def ratio(self, lang, num, den):
        n, d = self.W[lang] @ num, self.W[lang] @ den
        with np.errstate(invalid="ignore", divide="ignore"):
            b = n / d
        return (num.sum() / den.sum() if den.sum() > 0 else np.nan), b


def judge():
    D = os.path.join(RDATA, "judge_j2_2026-10-25")
    units = pd.read_csv(os.path.join(D, "run3_units_scored.csv"))
    cov = pd.read_csv(os.path.join(D, "run3_sentence_level_scores.csv"))
    TA = pd.read_csv(os.path.join(D, "run3_table_a_unit_means.csv"))
    TC = pd.read_csv(os.path.join(D, "run3_table_c_d_paired.csv"))
    B = Boot({l: set(cov[cov.lang == l].doc_id) for l in LANGS})

    def unit_stat(s):
        out = {}
        for l in LANGS:
            u = units[(units.system == s) & (units.lang == l) & units.score.notna()]
            if len(u):
                out[l] = B.ratio(l, *B.vec(l, u, "score"))
        return out

    def paired(sa, sb):
        out = {}
        for l in LANGS:
            ca, cb = (cov[(cov.system == s) & (cov.lang == l)].set_index(["doc_id", "sent_idx"]) for s in (sa, sb))
            if ca.empty or cb.empty:
                continue
            j = ca[["score"]].rename(columns={"score": "score_a"}).join(cb[["score"]].rename(columns={"score": "score_b"}), how="inner").reset_index()
            j = j[j.score_a.notna() & j.score_b.notna()].copy()
            j["d"] = j.score_a - j.score_b
            out[l] = B.ratio(l, *B.vec(l, j, "d")) + (len(j),)
        return out

    def macro(store, sel):
        v = float(np.mean([store[l][0] for l in sel]))
        lo, hi = ci(np.mean([store[l][1] for l in sel], axis=0))
        return v, lo, hi

    SYS = ["final2_whole", "final2_sentfix", "rl_whole", "nllb3b3_sent", "tpsy08_sent"]
    U = {s: unit_stat(s) for s in SYS}
    # check: reproduce the stored five-language macro rows
    for s in SYS:
        sel = [l for l in U[s] if l != "kin"]
        v, lo, hi = macro(U[s], sel)

    tex("tab_skew_langs.tex", "tab:skewlangs", cap2, "@{}lrrrrrrr@{}", ["Language", "SFT", "RL", "NLLB 3.3B", "gain", "gap", "SFT fin.\\ (\\%)", "RL vs NLLB"],
        [[x if x == "--" else (tm(x) if x.startswith("-") else x) for x in r] for r in R2], midrules=tuple(mid[:-1]))
    return out



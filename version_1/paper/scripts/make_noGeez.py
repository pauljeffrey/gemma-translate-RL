        return [label, str(o["n"]), f"{o['gap_mean']:.2f}", f"{o['gap_median']:.2f}", f"{100 * o['gap_share']:.1f}", f"{o['gain_mean']:.2f}", f"{o['gain_median']:.2f}"]

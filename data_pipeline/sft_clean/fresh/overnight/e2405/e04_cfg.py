#!/usr/bin/env python
"""E-04 / E-11 / E-14 run configs, generated from the EXECUTED configs (config.json of the stage-A and science-RL runs on the A100). Prints a yaml (JSON flow values) to stdout.

    python e04_cfg.py VARIANT SEED OUT_DIR [--steps 100] > rl_A_b64.yaml

VARIANT (stage A, 100 steps; features = dynamic sampling + advantage std floor + beam-guided member + reference domain; stage A ran steps 1-40 WITHOUT them and 41-400 WITH them):
  base     steps 1-40 of stage A as executed: all four features off (domain weights general 0.7 / news 0.3, reference_weight 0)          = E-11 arm (a) for the whole run
  full     steps 41+ of stage A as executed (config.json): features on (ds oversample 1.1, std floor 0.02, guide 0.25 beam 4, ref domain 0.15, reference_weight 0.35) = E-04 / E-11 arm (b)
  noref    full without the reference domain (domain weights general 0.7 / news 0.3, reference_weight 0)                                  = E-11 arm (c)
  noguide  full without the beam guide (guide_fraction 0, guide_adv_share_cap 0)                                                         = E-11 arm (d)
  kl025    full with kl_guard_threshold 0.25                                                                                              = E-11 arm (e, 0.25); kl 0.15 IS 'full' (stage A ran 0.15)
  sci      the executed science RL config (runs_385m_sci/final/config.json) started from the mixed-best model, 160 steps, no early stops (E-14); SEED/OUT_DIR as given
Everything else is the executed config. Not part of the recipe and changed for these runs only: hub_* = null (nothing is pushed), the translation archive is off, the dev predictions are saved, early stops /
extension / plateau stops are off so that the run has exactly the planned number of steps (none of them can act within 100 steps; for E-14 they are off so that the step count is 160 as executed).
"""
import json, re, sys

R = "/workspace/clean_rerun"
variant, seed, out_dir = sys.argv[1], int(sys.argv[2]), sys.argv[3]
steps = int(sys.argv[sys.argv.index("--steps") + 1]) if "--steps" in sys.argv else (160 if variant == "sci" else 100)
src = f"{R}/runs_385m_sci/final/config.json" if variant == "sci" else f"{R}/runs_385m/A/config.json"
c = json.load(open(src))["config"]
c.update(seed=seed, steps=steps, out_dir=out_dir, hub_repo_id=None, hub_branch=None, hub_latest_branch=None, archive=False, archive_path=None, save_dev_predictions=True,
         extend_if_improving=False, plateau_stop=False, early_stop=False, early_stop_dev=False, export_steps=[])
if variant == "sci":
    c.update(model_name=f"/dev/shm/rl_mixed_ckpt/best", planned_winddown_last=10)     # executed: dev_plateau at 150 -> WINDDOWN 10 steps (150 -> 160); planned_winddown_last 10 reproduces that lr schedule
else:
    c.update(curriculum_steps={"b64": steps}, planned_winddown_last=0)
    no_feat = dict(dynamic_sampling=False, dynamic_sampling_oversample=1.0, adv_std_floor=0.0, log_group_stats=False, guide_fraction=0.0, guide_adv_share_cap=0.0, domain_weights={"general": 0.7, "news": 0.3})
    rw = dict(c["reward"])
    if variant == "base":
        c.update(no_feat); rw["reference_weight"] = 0.0
    elif variant == "full":
        pass
    elif variant == "noref":
        c.update(domain_weights={"general": 0.7, "news": 0.3}); rw["reference_weight"] = 0.0
    elif variant == "noguide":
        c.update(guide_fraction=0.0, guide_adv_share_cap=0.0)
    elif variant == "kl025":
        c.update(kl_guard_threshold=0.25)
    else:
        sys.exit("unknown variant " + variant)
    c["reward"] = rw
print(f"# {variant} seed {seed} steps {steps}: generated by e04_cfg.py from {src} (executed config); see the script header for what differs")
for k, v in c.items():
    print(f"{k}: " + re.sub(r"(?<![\d.])(\d+)e([+-]?\d+)", r"\1.0e\2", json.dumps(v)))   # YAML 1.1 reads 2e-06 as a string, 2.0e-06 as a float

#!/bin/bash
# Runs on the A100 next to launch_growth.sh (which does stage A). Stage B in K shards (owner 2026-11-01: "shard stage B if it doesn't fit"):
#   wait for stage A (runs/g1a/summary.json), stop the idle stage-B waiter of launch_growth.sh, delete packed_g0 (every remaining pack now arrives again in the shards),
#   then for shard k = 1..K: wait for run/shards/s<k>/READY_LOCAL (pull_shards.sh), verify, train all parameters on it (init_from the previous run's last/trainer_state.pt),
#   delete the shard and the run before the previous one. LR: flat-ish between shards (cosine to 80 % of the peak, 3 % re-warm-up), the last shard decays to 10 %.
# Alerts in /workspace/work/logs/ALERT_a100.txt: [G1B_SHARD_STARTED] k, [G1B_SHARD_DONE] k, [G1B_DONE], [G1_SHARDS_FAILED] <reason>. Restartable: finished shards (summary.json) are skipped.
set -uo pipefail
K=${K:-6}
ROOT=/workspace/work; cd $ROOT/run; source $ROOT/env.sh
ALERT=$ROOT/logs/ALERT_a100.txt
export HF_HOME=$ROOT/hf_home PYTHONPATH=$ROOT/code:$ROOT/code/sft_clean/chain GEMMA_MT_PKG=$ROOT/code PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True HUB_NO_MODEL_CARD=1
PY=$ROOT/venv_train/bin/python
fail() { echo "$(date -u +%FT%TZ) [G1_SHARDS_FAILED] $1" >> $ALERT; echo "FAIL $1"; exit 1; }
wait_gpu() { local used; for i in $(seq 1 720); do used=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits | head -n 1 | tr -dc 0-9); [ "${used:-99999}" -lt 4000 ] && return 0; sleep 60; done; fail "GPU busy"; }
until [ -f runs/g1a/summary.json ]; do sleep 60; done
for p in $(pgrep -f "bash code/sft_clean/fresh/launch_growth.sh"); do kill $p 2>/dev/null; done        # idle: it would wait for the old single-bundle marker forever
rm -rf packed_g0 runs/g1a/last_prev
echo "$(date +%T) stage A done, packed_g0 deleted, $(df -BG --output=avail /workspace | tail -n 1 | tr -dc 0-9) GB free"
prev=runs/g1a
for k in $(seq 1 $K); do
  out=runs/g1b_s$k
  if [ -f $out/summary.json ]; then prev=$out; continue; fi
  until [ -f shards/s$k/READY_LOCAL ]; do sleep 30; done
  ( cd shards/s$k && sha256sum -c ../s$k.sha256 --quiet ) || fail "shard $k checksum"
  python3 - <<PY || fail "config $k"
import re
t = open("configs/growth1/g1b.yaml").read()
def setk(t, k, v): return re.sub(rf"^{k}:.*$", f"{k}: {v}", t, flags=re.M)
t = setk(t, "data_dir", "shards/s$k"); t = setk(t, "schedule_file", "shards/s$k/sched/schedule.npy"); t = setk(t, "out_dir", "$out"); t = setk(t, "run_name", "g1b_s$k")
t = setk(t, "hub_repo_id", "${HF_ORG}/gemma3-up6-g15-g1b-s$k"); t = setk(t, "init_from", "$prev/last/trainer_state.pt")
t = setk(t, "min_lr_ratio", "0.1" if $k == $K else "0.8")
open("configs/growth1/g1b_s$k.yaml", "w").write("# growth 1, stage B, shard $k of $K (all parameters trainable; generated by launch_shards.sh from g1b.yaml)\n" + t)
PY
  wait_gpu
  echo "$(date -u +%FT%TZ) [G1B_SHARD_STARTED] shard $k/$K from $prev, $(python3 -c "import numpy as np;print(np.load('shards/s$k/sched/schedule.npy').shape[0])") steps" >> $ALERT
  "$PY" -m gemma_mt.train_sft --config configs/growth1/g1b_s$k.yaml micro_batch_size=8 grad_accum_steps=4 >> logs/sft_g1b_s$k.log 2>&1
  rc=$?
  [ $rc = 0 ] && [ -f $out/summary.json ] || fail "shard $k exited rc=$rc (see $ROOT/run/logs/sft_g1b_s$k.log)"
  rm -rf shards/s$k shards/s$k.sha256 $out/last_prev
  [ "$prev" != "runs/g1a" ] || rm -rf runs/g1a/last                                                   # g1a's weights live on in shard 1's run
  [ $k -ge 2 ] && rm -rf runs/g1b_s$((k - 1))/last                                                    # the run before the previous one is no longer needed
  prev=$out
  echo "$(date -u +%FT%TZ) [G1B_SHARD_DONE] shard $k/$K finished; $(df -BG --output=avail /workspace | tail -n 1 | tr -dc 0-9) GB free" >> $ALERT
done
echo "$(date -u +%FT%TZ) [G1B_DONE] growth 1 finished: $K shards, final weights $prev/last" >> $ALERT
